import { describe, expect, it } from "vitest";
import { mealScore } from "@/lib/meal-score";
import { ZERO } from "@/lib/nutrition";
import { planVariant, suggestSwaps, swapFor, SWAPS } from "@/lib/swaps";
import { daySummary, parseGlucoseCsv, parseLibreTime, splitCsv } from "@/lib/glucose";
import { inferFlags } from "@/lib/flags";
import type { RuleProfile } from "@/lib/rules";

describe("meal score", () => {
  it("gives a balanced, lean, high-protein plate a high score", () => {
    const s = mealScore({ ...ZERO, protein: 35, fibre: 9, netCarbs: 15, sugar: 4, fat: 12, satFat: 2, mufa: 6, pufa: 3 }, null);
    expect(s.score).toBe(100);
    expect(s.parts.map((p) => p.max).reduce((a, b) => a + b, 0)).toBe(100);
  });
  it("penalises refined carbs with a high glycemic load, sugar and saturated fat", () => {
    const s = mealScore({ ...ZERO, protein: 10, fibre: 2, netCarbs: 70, sugar: 25, fat: 30, satFat: 15, mufa: 6, pufa: 1 }, 35);
    expect(s.score).toBeLessThan(25);
    expect(s.parts.find((p) => p.key === "carbs")!.points).toBe(0);
    expect(s.parts.find((p) => p.key === "carbs")!.note).toMatch(/GL 35 \(high\)/);
  });
  it("medium GL takes 3 points off the carb score", () => {
    expect(mealScore({ ...ZERO, netCarbs: 25 }, 15).parts.find((p) => p.key === "carbs")!.points).toBe(12);
  });
});

describe("swaps", () => {
  const alex: RuleProfile = { id: "alex", slug: "alex", name: "Alex", vegetarian: false, vegBreakfastAllowed: [], avoidFoods: ["milk"], noAlcohol: true, noAddedSugar: false, noRefinedStarch: true, maxNetCarbsPerMeal: 55, minProteinPerMeal: 20, maxCookMinutes: 40, omega3MinPerWeek: 1, omega3MaxPerWeek: 3 };
  const line = (id: string, slug: string, nameEn: string, forUserId: string | null = null) => ({ id, slug, nameEn, forUserId, grams: 150, ...inferFlags(nameEn) });
  it("suggests swaps only for lines that break this person's rules", () => {
    const s = suggestSwaps(alex, [line("1", "basmati-rice", "Basmati rice"), line("2", "red-wine", "Dry red wine"), line("3", "courgette", "Courgette"), line("4", "spaghetti", "Spaghetti", "sam"), line("5", "milk", "Milk")]);
    expect(s.map((x) => [x.lineId, x.reason])).toEqual([["1", "white rice/bread/pasta"], ["2", "contains alcohol"], ["5", "on the avoid list"]]);
  });
  it("never suggests a swap target on the person's own avoid list (courgette avoided → cauliflower)", () => {
    const noCourgette: RuleProfile = { ...alex, avoidFoods: ["milk", "courgette", "courgettes", "zucchini"] };
    const s = suggestSwaps(noCourgette, [line("1", "spaghetti", "Spaghetti"), line("2", "tagliatelle", "Tagliatelle", "alex")]);
    expect(s.map((x) => x.swap.to)).toEqual(["cauliflower", "cauliflower"]);
    expect(swapFor(noCourgette, "spaghetti")!.to).toBe("cauliflower");
    expect(swapFor(alex, "spaghetti")!.to).toBe("courgette");
    expect(swapFor({ ...noCourgette, avoidFoods: [...noCourgette.avoidFoods, "cauliflower"] }, "spaghetti")).toBeNull();
  });
  it("splits a shared line into the other person's portion + the swap for this person", () => {
    const rice = SWAPS.find((s) => s.from === "basmati-rice")!;
    const v = planVariant({ forUserId: null, grams: 150, qty: 150, unit: "g" }, rice, "alex", 2, ["alex", "sam"]);
    expect(v.keepFor).toEqual([{ forUserId: "sam", grams: 75, qty: 75 }]);
    expect(v.added).toEqual({ ingredientSlug: "cauliflower", forUserId: "alex", grams: 188, qty: 188, unit: "g" });
  });
  it("with three people the shared line becomes one portion line for each of the other two", () => {
    const rice = SWAPS.find((s) => s.from === "basmati-rice")!;
    const v = planVariant({ forUserId: null, grams: 300, qty: 300, unit: "g" }, rice, "sam", 3, ["alex", "sam", "robin"]);
    expect(v.keepFor).toEqual([{ forUserId: "alex", grams: 100, qty: 100 }, { forUserId: "robin", grams: 100, qty: 100 }]);
    expect(v.added?.forUserId).toBe("sam");
  });
  it("removes a person-only line when the swap is 'leave it out'", () => {
    const bread = SWAPS.find((s) => s.from === "sourdough-bread")!;
    expect(planVariant({ forUserId: "alex", grams: 60, qty: 60, unit: "g" }, bread, "alex", 2, ["alex", "sam"])).toEqual({ keepFor: [], added: null });
  });
});

describe("CGM CSV import", () => {
  it("parses a FreeStyle Libre EU export (historic + scan, skips notes)", () => {
    const csv = [
      "Glucose Data,Generated on,19-10-2026 10:00,Generated by,Alex",
      "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL,Non-numeric Rapid-Acting Insulin,Notes",
      "FreeStyle LibreLink,ABC,18-10-2026 07:45,0,112,,,",
      "FreeStyle LibreLink,ABC,18-10-2026 08:00,1,,131,,",
      "FreeStyle LibreLink,ABC,18-10-2026 08:05,6,,,,\"breakfast, eggs\"",
    ].join("\n");
    const r = parseGlucoseCsv(csv);
    expect(r.source).toBe("libre");
    expect(r.readings).toEqual([{ at: new Date("2026-10-18T07:45:00Z"), mgdl: 112 }, { at: new Date("2026-10-18T08:00:00Z"), mgdl: 131 }]);
  });
  it("converts mmol/L and US 12-hour timestamps", () => {
    const csv = ["Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L", "x,y,10-18-2026 01:30 PM,0,6.2,"].join("\n");
    const r = parseGlucoseCsv(csv);
    expect(r.readings[0]).toEqual({ at: new Date("2026-10-18T13:30:00Z"), mgdl: 112 });
  });
  it("parses a Dexcom Clarity export (EGV rows only, Low/High skipped)", () => {
    const csv = [
      "Index,Timestamp (YYYY-MM-DDThh:mm:ss),Event Type,Event Subtype,Patient Info,Device Info,Source Device ID,Glucose Value (mg/dL),Insulin Value (u),Carb Value (grams)",
      "1,,FirstName,,Alex,,,,,",
      "10,2026-10-18T08:05:00,EGV,,,,iPhone,118,,",
      "11,2026-10-18T08:10:00,EGV,,,,iPhone,Low,,",
      "12,2026-10-18T08:15:00,Carbs,,,,iPhone,,,30",
    ].join("\n");
    const r = parseGlucoseCsv(csv);
    expect(r.source).toBe("dexcom");
    expect(r.readings).toEqual([{ at: new Date("2026-10-18T08:05:00Z"), mgdl: 118 }]);
    expect(r.skipped).toBe(1);
  });
  it("rejects files that are not CGM exports", () => {
    expect(() => parseGlucoseCsv("a,b,c\n1,2,3")).toThrow(/Not a FreeStyle Libre or Dexcom/);
  });
  it("splits quoted CSV, parses dates and summarises a day", () => {
    expect(splitCsv('a,"b, c","d ""q"""')).toEqual(["a", "b, c", 'd "q"']);
    expect(parseLibreTime("31.12.2026 23:59")?.toISOString()).toBe("2026-12-31T23:59:00.000Z");
    expect(parseLibreTime("32-01-2026 10:00")).toBeNull();
    expect(daySummary([{ at: new Date(), mgdl: 60 }, { at: new Date(), mgdl: 120 }, { at: new Date(), mgdl: 190 }, { at: new Date(), mgdl: 150 }])).toEqual({ avg: 130, inRange: 50, min: 60, max: 190 });
    expect(daySummary([])).toBeNull();
  });
});
